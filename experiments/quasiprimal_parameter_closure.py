#!/usr/bin/env python3
"""Bounded oracle for parameter-closure abstraction in finite quasi-primal algebras.

The generic theorem is proved in the accompanying note.  This script attacks it
on two three-element algebras by exhaustive enumeration of every binary table,
every raw parameter set, every relevant internal isomorphism, and every minimum
parameter budget.
"""
from __future__ import annotations

import argparse
import json
from itertools import permutations, product
from pathlib import Path

Q = (0, 1, 2)
T2 = tuple(product(Q, repeat=2))
ALL_TABLES = tuple(product(Q, repeat=len(T2)))
SUBSETS = tuple(
    frozenset(Q[i] for i in range(len(Q)) if mask & (1 << i))
    for mask in range(1 << len(Q))
)


def disc(x: int, y: int, z: int) -> int:
    return z if x == y else x


def q_u(x: int) -> int:
    return {0: 1, 1: 0, 2: 1}[x]


def closure(seed: frozenset[int], unary_ops: tuple) -> frozenset[int]:
    """Subuniverse generated by seed for the calibrations (disc is conservative)."""
    out = set(seed)
    while True:
        old = set(out)
        for op in unary_ops:
            out.update(op(x) for x in old)
        if out == old:
            return frozenset(out)


def nonempty_subuniverses(unary_ops: tuple) -> tuple[frozenset[int], ...]:
    return tuple(S for S in SUBSETS if S and closure(S, unary_ops) == S)


def internal_isomorphisms(
    core: frozenset[int], unary_ops: tuple
) -> tuple[tuple[frozenset[int], frozenset[int], dict[int, int]], ...]:
    """Internal isomorphisms of the expansion naming every element of core."""
    subuniverses = nonempty_subuniverses(unary_ops)
    out = []
    for source in subuniverses:
        if not core <= source:
            continue
        source_list = tuple(sorted(source))
        for target in subuniverses:
            if not core <= target or len(source) != len(target):
                continue
            for image in permutations(sorted(target)):
                mapping = dict(zip(source_list, image, strict=True))
                if any(mapping[x] != x for x in core):
                    continue
                if any(mapping[op(x)] != op(mapping[x]) for op in unary_ops for x in source):
                    continue
                # Every bijection preserves the discriminator, but check explicitly.
                if any(
                    mapping[disc(x, y, z)]
                    != disc(mapping[x], mapping[y], mapping[z])
                    for x, y, z in product(source_list, repeat=3)
                ):
                    continue
                out.append((source, target, mapping))
    return tuple(out)


def preserves(
    table: tuple[int, ...],
    isomorphisms: tuple[tuple[frozenset[int], frozenset[int], dict[int, int]], ...],
) -> bool:
    f = dict(zip(T2, table, strict=True))
    for source, _target, mapping in isomorphisms:
        for z in product(sorted(source), repeat=2):
            value = f[z]
            if value not in source:
                return False
            mapped_z = tuple(mapping[x] for x in z)
            if f[mapped_z] != mapping[value]:
                return False
    return True



def has_pointed_extension_property(core: frozenset[int], unary_ops: tuple) -> bool:
    """Whether every nontrivial core-fixing internal isomorphism extends globally."""
    isomorphisms = internal_isomorphisms(core, unary_ops)
    carrier = frozenset(Q)
    automorphisms = tuple(
        item
        for item in isomorphisms
        if item[0] == carrier and item[1] == carrier
    )
    for source, _target, mapping in isomorphisms:
        if len(source) <= 1:
            continue
        if not any(
            all(auto_mapping[value] == image for value, image in mapping.items())
            for _auto_source, _auto_target, auto_mapping in automorphisms
        ):
            return False
    return True


def maximal_nonextendable_fixed_cores(
    unary_ops: tuple,
) -> tuple[int, tuple[frozenset[int], ...]]:
    """Compile nonextendable partial symmetries to maximal closed fixed cores."""
    isomorphisms = internal_isomorphisms(frozenset(), unary_ops)
    carrier = frozenset(Q)
    automorphisms = tuple(
        item
        for item in isomorphisms
        if item[0] == carrier and item[1] == carrier
    )
    fixed_cores = set()
    nonextendable_count = 0
    for source, _target, mapping in isomorphisms:
        if len(source) <= 1:
            continue
        if any(
            all(auto_mapping[value] == image for value, image in mapping.items())
            for _auto_source, _auto_target, auto_mapping in automorphisms
        ):
            continue
        nonextendable_count += 1
        fixed = frozenset(value for value in source if mapping[value] == value)
        assert closure(fixed, unary_ops) == fixed
        fixed_cores.add(fixed)
    maximal = tuple(
        sorted(
            (fixed for fixed in fixed_cores if not any(fixed < other for other in fixed_cores)),
            key=lambda values: (len(values), tuple(values)),
        )
    )
    return nonextendable_count, maximal


def check_patchability_descent(
    unary_ops: tuple,
) -> tuple[int, tuple[frozenset[int], ...], int, tuple[frozenset[int], ...]]:
    mismatches = 0
    good = []
    nonextendable_count, maximal_fixed = maximal_nonextendable_fixed_cores(unary_ops)
    for C in SUBSETS:
        raw_answer = has_pointed_extension_property(C, unary_ops)
        core = closure(C, unary_ops)
        abstract_answer = has_pointed_extension_property(core, unary_ops)
        obstruction_answer = all(not core <= fixed for fixed in maximal_fixed)
        if not (raw_answer == abstract_answer == obstruction_answer):
            mismatches += 1
        if raw_answer:
            good.append(C)
    assert mismatches == 0
    return mismatches, tuple(good), nonextendable_count, maximal_fixed

def operation_sets(unary_ops: tuple) -> dict[frozenset[int], frozenset[tuple[int, ...]]]:
    cores = tuple(sorted({closure(C, unary_ops) for C in SUBSETS}, key=lambda S: (len(S), tuple(S))))
    result = {}
    for core in cores:
        isomorphisms = internal_isomorphisms(core, unary_ops)
        result[core] = frozenset(
            table for table in ALL_TABLES if preserves(table, isomorphisms)
        )
    return result


def raw_parameter_languages(
    unary_ops: tuple,
    by_core: dict[frozenset[int], frozenset[tuple[int, ...]]],
) -> dict[frozenset[int], frozenset[tuple[int, ...]]]:
    return {C: by_core[closure(C, unary_ops)] for C in SUBSETS}


def check_full_abstraction(
    unary_ops: tuple,
    raw: dict[frozenset[int], frozenset[tuple[int, ...]]],
) -> tuple[int, int]:
    false_merges = 0
    false_splits = 0
    for left in SUBSETS:
        for right in SUBSETS:
            same_abstract = closure(left, unary_ops) == closure(right, unary_ops)
            same_language = raw[left] == raw[right]
            if same_abstract and not same_language:
                false_merges += 1
            if same_language and not same_abstract:
                false_splits += 1
    assert false_merges == false_splits == 0
    return false_merges, false_splits


def generator_rank(core: frozenset[int], unary_ops: tuple) -> int:
    return min(len(C) for C in SUBSETS if closure(C, unary_ops) == core)


def minimum_budget_distribution(
    unary_ops: tuple,
    by_core: dict[frozenset[int], frozenset[tuple[int, ...]]],
) -> dict[int, int]:
    ranks = {core: generator_rank(core, unary_ops) for core in by_core}
    result: dict[int, int] = {}
    for table in ALL_TABLES:
        budget = min(ranks[core] for core, functions in by_core.items() if table in functions)
        result[budget] = result.get(budget, 0) + 1
    return dict(sorted(result.items()))


def minimum_raw_sets(
    table: tuple[int, ...], raw: dict[frozenset[int], frozenset[tuple[int, ...]]]
) -> tuple[frozenset[int], ...]:
    feasible = tuple(C for C in SUBSETS if table in raw[C])
    minimum_size = min(map(len, feasible))
    return tuple(C for C in feasible if len(C) == minimum_size)


def quackenbush_check() -> tuple[dict[str, object], dict[frozenset[int], frozenset[tuple[int, ...]]]]:
    unary_ops = (q_u,)
    by_core = operation_sets(unary_ops)
    raw = raw_parameter_languages(unary_ops, by_core)
    false_merges, false_splits = check_full_abstraction(unary_ops, raw)
    (
        patchability_mismatches,
        good_parameter_sets,
        nonextendable_count,
        maximal_fixed,
    ) = check_patchability_descent(unary_ops)

    empty = frozenset()
    binary = frozenset({0, 1})
    full = frozenset(Q)
    assert set(by_core) == {empty, binary, full}
    assert len(by_core[empty]) == 972
    assert len(by_core[binary]) == 3888
    assert len(by_core[full]) == 19683
    assert closure(frozenset({0}), unary_ops) == binary
    assert closure(frozenset({1}), unary_ops) == binary
    assert closure(frozenset({2}), unary_ops) == full
    assert frozenset() not in good_parameter_sets
    assert all(C in good_parameter_sets for C in SUBSETS if C)
    assert nonextendable_count == 1
    assert maximal_fixed == (frozenset(),)

    strata = {
        "original": len(by_core[empty]),
        "binary_only": len(by_core[binary] - by_core[empty]),
        "full_only": len(by_core[full] - by_core[binary]),
    }
    assert strata == {"original": 972, "binary_only": 2916, "full_only": 15795}
    budgets = minimum_budget_distribution(unary_ops, by_core)
    assert budgets == {0: 972, 1: 18711}
    return ({
        "core_counts": {tuple(sorted(core)): len(functions) for core, functions in by_core.items()},
        "strata": strata,
        "budgets": budgets,
        "false_merges": false_merges,
        "false_splits": false_splits,
        "patchability_mismatches": patchability_mismatches,
        "good_parameter_sets": len(good_parameter_sets),
        "nonextendable_count": nonextendable_count,
        "maximal_fixed_cores": tuple(tuple(sorted(core)) for core in maximal_fixed),
    }, raw)


def pure_discriminator_check() -> dict[str, object]:
    unary_ops: tuple = ()
    by_core = operation_sets(unary_ops)
    raw = raw_parameter_languages(unary_ops, by_core)
    false_merges, false_splits = check_full_abstraction(unary_ops, raw)
    (
        patchability_mismatches,
        good_parameter_sets,
        nonextendable_count,
        maximal_fixed,
    ) = check_patchability_descent(unary_ops)
    assert len(good_parameter_sets) == len(SUBSETS)
    assert nonextendable_count == 0
    assert maximal_fixed == ()

    expected_by_size = {0: 2, 1: 24, 2: 3888, 3: 19683}
    for core, functions in by_core.items():
        assert len(functions) == expected_by_size[len(core)]

    budgets = minimum_budget_distribution(unary_ops, by_core)
    assert budgets == {0: 2, 1: 66, 2: 9932, 3: 9683}

    minimum_multiplicity: dict[int, int] = {}
    for table in ALL_TABLES:
        count = len(minimum_raw_sets(table, raw))
        minimum_multiplicity[count] = minimum_multiplicity.get(count, 0) + 1
    assert minimum_multiplicity == {1: 18151, 2: 1488, 3: 44}

    # f(x,y)=2 exactly at (2,2), else 0.  It has two incomparable minimum cores.
    spike = tuple(2 if z == (2, 2) else 0 for z in T2)
    mins = set(minimum_raw_sets(spike, raw))
    assert mins == {frozenset({0, 1}), frozenset({0, 2})}
    assert spike not in raw[frozenset({0})]

    return {
        "counts_by_core_size": expected_by_size,
        "budgets": budgets,
        "minimum_multiplicity": minimum_multiplicity,
        "witness_minimum_cores": tuple(sorted(tuple(sorted(C)) for C in mins)),
        "false_merges": false_merges,
        "false_splits": false_splits,
        "patchability_mismatches": patchability_mismatches,
        "good_parameter_sets": len(good_parameter_sets),
        "nonextendable_count": nonextendable_count,
        "maximal_fixed_cores": tuple(tuple(sorted(core)) for core in maximal_fixed),
    }


def parameter_id(C: frozenset[int]) -> str:
    return "none" if not C else "set_" + "_".join(map(str, sorted(C)))


def morph_corpus(
    raw: dict[frozenset[int], frozenset[tuple[int, ...]]]
) -> dict[str, object]:
    queries = [f"table_{index:05d}" for index in range(len(ALL_TABLES))]
    objects = []
    for C in SUBSETS:
        functions = raw[C]
        answers = {
            query: table in functions
            for query, table in zip(queries, ALL_TABLES, strict=True)
        }
        objects.append({
            "id": parameter_id(C),
            "abstract": sorted(closure(C, (q_u,))),
            "answers": answers,
        })
    operations = {
        f"add_{value}": {
            parameter_id(C): parameter_id(frozenset(set(C) | {value}))
            for C in SUBSETS
        }
        for value in Q
    }
    return {
        "schema": "minimum-sufficient-abstraction/finite-corpus/v1",
        "claim_id": "quackenbush-parameter-closure-binary-polynomial-language",
        "require_minimal": True,
        "queries": queries,
        "objects": objects,
        "operations": operations,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--emit-morph-corpus", type=Path)
    args = parser.parse_args()

    q, q_raw = quackenbush_check()
    p = pure_discriminator_check()
    if args.emit_morph_corpus:
        args.emit_morph_corpus.parent.mkdir(parents=True, exist_ok=True)
        args.emit_morph_corpus.write_text(
            json.dumps(morph_corpus(q_raw), indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )

    print("PASS quasi-primal parameter-closure abstraction")
    print("Quackenbush binary operation counts by closed core:", q["core_counts"])
    print("Quackenbush semantic strata:", q["strata"])
    print("Quackenbush minimum parameter budget distribution:", q["budgets"])
    print("pure discriminator counts by core size:", p["counts_by_core_size"])
    print("pure discriminator minimum parameter budget distribution:", p["budgets"])
    print("pure discriminator minimum-set multiplicities:", p["minimum_multiplicity"])
    print("no-least-core witness minimum cores:", p["witness_minimum_cores"])
    print("Morph false merges / false splits: 0 / 0 on both calibrations")
    print("patchability closure/obstruction-descent mismatches: 0 on both calibrations")
    print("Quackenbush maximal closed obstruction cores:", q["maximal_fixed_cores"])
    print("pure discriminator maximal closed obstruction cores:", p["maximal_fixed_cores"])


if __name__ == "__main__":
    main()
