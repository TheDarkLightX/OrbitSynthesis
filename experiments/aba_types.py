#!/usr/bin/env python3
"""Exact finite oracle for complete types of atomless Boolean algebras.

Representation
--------------
For k variables there are 2^k Boolean minterm/Venn cells.  A complete
parameter-free k-type of ABA is represented by a nonzero integer whose bits
say which cells are nonzero.  Hence the legal type masks are exactly
1 .. 2^(2^k)-1.

This is a reference/falsification implementation, not a performance engine.
"""

from __future__ import annotations

from collections.abc import Callable, Iterable, Sequence

Delta = tuple[str, int]  # ("eq0" | "neq0", minterm-support mask of term)


def valuation_bits(cell: int, k: int) -> tuple[int, ...]:
    """Decode a Boolean-cube cell; variable i is bit i."""
    return tuple((cell >> i) & 1 for i in range(k))


def type_count(k: int) -> int:
    """Exact number of complete parameter-free k-types of ABA."""
    return (1 << (1 << k)) - 1


def iter_types(k: int) -> range:
    """Enumerate all complete k-types as nonempty minterm-support masks."""
    return range(1, 1 << (1 << k))


def restrict_support(type_mask: int, k: int, keep: tuple[int, ...]) -> int:
    """Forget coordinates by projecting nonzero fine cells to coarse cells.

    A coarse cell is nonzero iff at least one source cell refining it is
    nonzero.  This is the exact restriction map on complete ABA types.
    """
    out = 0
    for cell in range(1 << k):
        if not ((type_mask >> cell) & 1):
            continue
        bits = valuation_bits(cell, k)
        coarse = 0
        for new_pos, old_pos in enumerate(keep):
            coarse |= bits[old_pos] << new_pos
        out |= 1 << coarse
    return out


def term_mask(k: int, predicate: Callable[[tuple[int, ...]], bool]) -> int:
    """Compile a simple Boolean term by its truth function on {0,1}^k.

    The returned mask says which minterm cells occur in its normal form.
    """
    out = 0
    for cell in range(1 << k):
        if predicate(valuation_bits(cell, k)):
            out |= 1 << cell
    return out


def eq0(term_support_mask: int) -> Delta:
    return ("eq0", term_support_mask)


def neq0(term_support_mask: int) -> Delta:
    return ("neq0", term_support_mask)


def eval_delta(type_mask: int, delta: Delta) -> bool:
    """Evaluate t=0 or t!=0 on a complete support-pattern type."""
    kind, mask = delta
    intersects = bool(type_mask & mask)
    if kind == "eq0":
        return not intersects
    if kind == "neq0":
        return intersects
    raise ValueError(f"unknown delta kind: {kind}")


def truth_signature(type_mask: int, deltas: Sequence[Delta]) -> tuple[bool, ...]:
    return tuple(eval_delta(type_mask, d) for d in deltas)


def realized_truth_signatures(k: int, deltas: Sequence[Delta]) -> set[tuple[bool, ...]]:
    """Atoms of the Boolean algebra generated by Delta, as truth vectors."""
    return {truth_signature(t, deltas) for t in iter_types(k)}


def feature_signature_t3(type_mask: int, deltas: Sequence[Delta]):
    """Information used by the ocLTL three-variable compatibility picture.

    Variable order is m=0, x=1, y=2.  The signature records:
      * the restricted (m,x)-type,
      * the y-type used as successor memory,
      * the Delta truth vector.

    This is an experimental representation of the feature quotient described
    in research/CONJECTURES.md; it is not yet claimed globally minimal.
    """
    mx_type = restrict_support(type_mask, 3, (0, 1))
    successor_memory_type = restrict_support(type_mask, 3, (2,))
    return mx_type, successor_memory_type, truth_signature(type_mask, deltas)


def realized_feature_signatures_t3(deltas: Sequence[Delta]) -> set[tuple]:
    return {feature_signature_t3(t, deltas) for t in iter_types(3)}


def generated_algebra_size(k: int, deltas: Sequence[Delta]) -> int:
    """|B_Delta| = 2^(number of realized truth signatures)."""
    r_delta = len(realized_truth_signatures(k, deltas))
    return 1 << r_delta


def self_test() -> None:
    assert [type_count(k) for k in range(1, 5)] == [3, 15, 255, 65535]

    for k in (1, 2, 3):
        assert sum(1 for _ in iter_types(k)) == type_count(k)

    # Every smaller type extends to a larger one: restriction is surjective.
    for k in (2, 3):
        image = {
            restrict_support(t, k, tuple(range(k - 1)))
            for t in iter_types(k)
        }
        assert image == set(iter_types(k - 1))

    # Three sample data predicates over (m,x,y).
    m, x, y = 0, 1, 2
    y_xor_x = term_mask(3, lambda b: bool(b[y] ^ b[x]))
    y_and_m = term_mask(3, lambda b: bool(b[y] & b[m]))
    y_or_x = term_mask(3, lambda b: bool(b[y] | b[x]))

    deltas = [
        eq0(y_xor_x),   # y = x
        eq0(y_and_m),   # y & m = 0
        neq0(y_or_x),   # y | x != 0
    ]

    truth = realized_truth_signatures(3, deltas)
    features = realized_feature_signatures_t3(deltas)

    # Only five of the eight syntactic Delta truth vectors are realizable.
    assert len(truth) == 5
    assert generated_algebra_size(3, deltas) == 32

    # These predicates + compatibility features distinguish 63 signatures,
    # versus all 255 complete 3-types.
    assert len(features) == 63


def main() -> None:
    self_test()
    print("ABA complete-type counts")
    for k in range(1, 5):
        print(f"  |T_{k}| = {type_count(k)}")

    m, x, y = 0, 1, 2
    deltas = [
        eq0(term_mask(3, lambda b: bool(b[y] ^ b[x]))),
        eq0(term_mask(3, lambda b: bool(b[y] & b[m]))),
        neq0(term_mask(3, lambda b: bool(b[y] | b[x]))),
    ]
    r = len(realized_truth_signatures(3, deltas))
    q = len(realized_feature_signatures_t3(deltas))
    print(f"sample Delta: realized truth signatures = {r}")
    print(f"sample Delta: generated Boolean algebra size = {1 << r}")
    print(f"sample Delta: ocLTL-style feature signatures = {q} / 255")


if __name__ == "__main__":
    main()
